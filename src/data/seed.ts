function applySafety(it: Itinerary): void {
  const tag = (s: { id: string; safety?: SafetyLevel }) => {
    const lvl = SAFETY_BY_ID[s.id]
    if (lvl) s.safety = lvl
  }
  it.days.forEach((d) => d.stops.forEach(tag))
  it.banks.forEach((b) => b.stops.forEach(tag))
}

